"""Generic Harbor-task resources server, filling a gap NeMo Gym does not ship.

Gym's own Harbor task-loading machinery (nemo_gym.tasks.harbor) fully parses
task.toml/instruction.md/tests folders and generates a run config that routes to a
resources server named "harbor" -- but that resources server's implementation does
not exist upstream (checked against NVIDIA-NeMo/Gym's current HEAD, not only our
pin). This module is that missing implementation, built new in this repo and
discovered via --search-dir rather than vendored into the installed package.

Harbor's materialized task row carries only {"_ng_digest": <digest>} (see
nemo_gym.tasks.harbor.materialize.materialize_task); the task's actual
instruction/environment/tests live on disk and must be reconstructed here, keyed
by the tasksets/datasets mapping this server's own config carries (already
generated correctly by materialize.run_config). No existing resources server
does this reconstruction step -- it is the one genuinely new piece of logic.
"""

import logging
from glob import glob
from pathlib import Path
from typing import Any, ClassVar

from fastapi import HTTPException, Request
from nemo_gym.base_resources_server import (
    BaseResourcesServerConfig,
    BaseVerifyRequest,
    BaseVerifyResponse,
    ResourcesCloseSessionRequest,
    ResourcesCloseSessionResponse,
    ResourcesSeedSessionRequest,
    ResourcesSeedSessionResponse,
    ReverifyMode,
    SimpleResourcesServer,
)
from nemo_gym.global_config import get_global_config_dict
from nemo_gym.sandbox import AsyncSandbox, SandboxResources, SandboxSpec, create_provider
from nemo_gym.sandbox.access import DirectSandboxConnection, SandboxAccess
from nemo_gym.sandbox.config import resolve_provider_config, resolve_provider_metadata
from nemo_gym.server_utils import SESSION_ID_KEY, is_nemo_gym_fastapi_entrypoint
from nemo_gym.tasks.harbor.digest import DIGEST_KEY
from nemo_gym.tasks.harbor.task import HarborTask, HarborTaskError, load_task

LOG = logging.getLogger(__name__)

REWARD_JSON_PATH = "/logs/verifier/reward.json"
REWARD_TXT_PATH = "/logs/verifier/reward.txt"
# Our own convention (external Harbor docs name both files but specify no JSON
# schema): prefer this key in reward.json, fall back to a bare float in reward.txt.
REWARD_JSON_KEY = "reward"


class HarborResourcesServerConfig(BaseResourcesServerConfig):
    # Live shell state in a stopped sandbox cannot be safely replayed.
    REVERIFY_MODE: ClassVar[ReverifyMode] = ReverifyMode.UNSUPPORTED

    sandbox_provider: str = "sandbox"
    # {taskset: {"folder": str, "tasks": {task_id: digest}}} -- as
    # nemo_gym.tasks.harbor.materialize.run_config generates it. The resources server has no
    # other way to find a task's files: the materialized row only carries a digest.
    tasksets: dict[str, dict[str, Any]]
    datasets: list[dict[str, Any]] = []
    # Generated by materialize.run_config but not acted on in v1 -- see
    # docs/adaptive-task-runner.md's open questions. A natural follow-up is copying
    # /logs/verifier/* here before the sandbox stops.
    artifacts_dir: str | None = None
    # NOT populated by materialize.run_config (it only sets
    # sandbox_provider/tasksets/datasets/artifacts_dir). Supply sandbox_config via an operator
    # +config_paths overlay to set ttl_s/resources/provider_options/etc; empty defaults here
    # otherwise.
    sandbox_config: dict[str, Any] = {}
    verify_timeout_seconds: float = 600.0


class HarborVerifyResponse(BaseVerifyResponse):
    test_output: str = ""
    evaluation_completed: bool = False


class HarborResourcesServer(SimpleResourcesServer):
    config: HarborResourcesServerConfig

    def model_post_init(self, context: Any, /) -> None:
        self._sessions: dict[str, tuple[AsyncSandbox, HarborTask]] = {}

    def _load_task(
        self, task_id_taskset: str, task_id: str, task_data: dict[str, Any]
    ) -> HarborTask:
        taskset = self.config.tasksets.get(task_id_taskset)
        if taskset is None:
            raise HTTPException(422, f"Unknown Harbor taskset {task_id_taskset!r}")
        expected_digest = taskset["tasks"].get(task_id)
        if expected_digest is None or task_data.get(DIGEST_KEY) != expected_digest:
            raise HTTPException(409, "harbor task digest missing or stale at seed time")
        folder = Path(taskset["folder"]) / task_id
        try:
            task = load_task(folder)
        except HarborTaskError as exc:
            raise HTTPException(422, str(exc)) from exc
        if task.digest != expected_digest:
            raise HTTPException(409, "harbor task folder changed since materialization")
        if not task.needs_sandbox:
            raise HTTPException(422, "Harbor task declares no image/Dockerfile; unsupported in v1")
        verifier = task.config.verifier
        if verifier.environment_mode == "separate" or verifier.environment is not None:
            raise HTTPException(422, "verifier environment_mode='separate' is out of scope for v1")
        return task

    async def _upload_tree(self, sandbox: AsyncSandbox, local_dir: Path, remote_dir: str) -> None:
        for relative in glob("**", root_dir=str(local_dir), recursive=True):
            local_fpath = local_dir / relative
            if not local_fpath.is_file():
                continue
            remote_fpath = f"{remote_dir}/{relative}"
            mkdir_result = await sandbox.exec(f"mkdir -p {Path(remote_fpath).parent}", timeout_s=30)
            if mkdir_result.return_code != 0:
                raise RuntimeError(f"Failed to stage {remote_fpath}: {mkdir_result.stderr}")
            await sandbox.upload(local_fpath, remote_fpath)

    async def _collect_reward(self, sandbox: AsyncSandbox) -> float:
        import json
        import tempfile

        with tempfile.TemporaryDirectory() as scratch:
            scratch_path = Path(scratch)
            json_check = await sandbox.exec(f"test -f {REWARD_JSON_PATH}", timeout_s=30)
            if json_check.return_code == 0:
                local = scratch_path / "reward.json"
                await sandbox.download(REWARD_JSON_PATH, local)
                payload = json.loads(local.read_text())
                return float(payload[REWARD_JSON_KEY])
            txt_check = await sandbox.exec(f"test -f {REWARD_TXT_PATH}", timeout_s=30)
            if txt_check.return_code == 0:
                local = scratch_path / "reward.txt"
                await sandbox.download(REWARD_TXT_PATH, local)
                return float(local.read_text().strip())
            raise RuntimeError(f"Neither {REWARD_JSON_PATH} nor {REWARD_TXT_PATH} was written")

    async def _safe_stop(self, sandbox: AsyncSandbox) -> None:
        try:
            await sandbox.stop()
        except Exception:
            LOG.exception("Failed to stop Harbor sandbox")

    async def seed_session(
        self, request: Request, body: ResourcesSeedSessionRequest
    ) -> ResourcesSeedSessionResponse:
        task = self._load_task(body.task_id.taskset, body.task_id.task_id, body.task_data)
        folder = Path(self.config.tasksets[body.task_id.taskset]["folder"]) / body.task_id.task_id

        global_config = get_global_config_dict()
        provider_config = resolve_provider_config(self.config.sandbox_provider, global_config)
        provider = create_provider(provider_config)
        sandbox = AsyncSandbox(provider)
        resources = SandboxResources.from_mapping(self.config.sandbox_config.get("resources", {}))
        spec = SandboxSpec(
            image=task.image,
            workdir=task.workdir,
            env=task.env,
            ttl_s=self.config.sandbox_config.get("ttl_s"),
            ready_timeout_s=self.config.sandbox_config.get("ready_timeout_s"),
            resources=resources,
            files={},
            entrypoint=None,
            metadata=(
                resolve_provider_metadata(self.config.sandbox_provider, global_config)
                | self.config.sandbox_config.get("metadata", {})
                | {"harbor_task_id": task.task_id[:63]}
            ),
            provider_options=self.config.sandbox_config.get("provider_options", {}),
        )
        try:
            await sandbox.start(spec)
            await sandbox.exec("mkdir -p /logs/verifier", timeout_s=30)
            await self._upload_tree(sandbox, folder / "tests", "/tests")
            working_directory = await sandbox.exec("pwd", timeout_s=30)
        except BaseException:
            await self._safe_stop(sandbox)
            raise

        session_id = body.resources_session_id
        self._sessions[session_id] = (sandbox, task)
        request.session[SESSION_ID_KEY] = session_id
        workdir = (working_directory.stdout or "").strip()
        return ResourcesSeedSessionResponse(
            resources_session_id=session_id,
            sandbox_access=SandboxAccess(
                connection=DirectSandboxConnection(
                    provider_config_ref=self.config.sandbox_provider,
                    descriptor=await sandbox.serialize(),
                ),
                workdir=workdir or task.workdir or "/",
            ),
        )

    async def close_resources_session(
        self, body: ResourcesCloseSessionRequest
    ) -> ResourcesCloseSessionResponse:
        # Defensive: a rollout can be cancelled/time out before /verify ever runs, which would
        # otherwise leak a live sandbox against the shared gateway.
        entry = self._sessions.pop(body.resources_session_id, None)
        if entry is not None:
            sandbox, _task = entry
            await self._safe_stop(sandbox)
        return ResourcesCloseSessionResponse(resources_session_id=body.resources_session_id)

    async def verify(self, request: Request, body: BaseVerifyRequest) -> HarborVerifyResponse:
        session_id = request.session.get(SESSION_ID_KEY)
        entry = self._sessions.pop(session_id, None) if session_id else None
        if entry is None:
            # Infra failure, never raise out of /verify: a masked zero keeps Gym's failure
            # accounting sane instead of crashing the whole rollout.
            return HarborVerifyResponse(
                **body.model_dump(),
                reward=0.0,
                mask_sample=True,
                failure_kind="harbor:verifier_infra_error",
                failure_reason="no active sandbox session at verify time",
            )
        sandbox, _task = entry
        try:
            result = await sandbox.exec(
                "bash /tests/test.sh", timeout_s=self.config.verify_timeout_seconds
            )
            reward = await self._collect_reward(sandbox)
            return HarborVerifyResponse(
                **body.model_dump(),
                reward=reward,
                evaluation_completed=True,
                test_output=(result.stderr or "") + (result.stdout or ""),
            )
        except Exception as exc:
            return HarborVerifyResponse(
                **body.model_dump(),
                reward=0.0,
                mask_sample=True,
                failure_kind="harbor:verifier_infra_error",
                failure_reason=str(exc)[:2000],
            )
        finally:
            await self._safe_stop(sandbox)


if __name__ == "__main__":
    HarborResourcesServer.run_webserver()
elif is_nemo_gym_fastapi_entrypoint(__file__):
    app = HarborResourcesServer.run_webserver()  # noqa: F401
